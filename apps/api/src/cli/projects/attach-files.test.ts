const noIndex = async () => []

function tmp(prefix: string): string {
  const dir = mkdtempSync(join(tmpdir(), prefix))
  tmpDirs.push(dir)
  return dir
}

function writeNdjson(records: unknown[]): string {
  const file = join(tmp("cli-attach-ndjson-"), "batches.ndjson")
  writeFileSync(file, `${records.map((r) => JSON.stringify(r)).join("\n")}\n`)
  return file
}

/** A files dir holding generated bytes at the given relative paths. */
function filesDir(files: Record<string, Buffer>): string {
  const dir = tmp("cli-attach-files-")
  for (const [rel, bytes] of Object.entries(files)) {
    mkdirSync(join(dir, rel, ".."), { recursive: true })
    writeFileSync(join(dir, rel), bytes)
  }
  return dir
}

const bytes = (n: number) => crypto.randomBytes(n)
const ref = () => `AT-${crypto.randomUUID().slice(0, 8)}`

