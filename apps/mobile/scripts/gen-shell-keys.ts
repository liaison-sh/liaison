#!/usr/bin/env bun
// SPDX-License-Identifier: FSL-1.1-ALv2
//
// The iOS served shell verifies with the same pinned app-signing keys and
// compiled revocation floor as every other client: packages/shared/src/
// app-signing/keys.json, the one source of truth. Swift cannot read that file
// at run time from outside its bundle, so this writes it out as
// ios/LiaisonShell/Sources/LiaisonShell/PinnedKeys.swift, and
// shell-keys.test.ts fails when the two differ (run this to fix it).
//
//   bun run scripts/gen-shell-keys.ts          write the Swift file
//   bun run scripts/gen-shell-keys.ts --check  exit 1 when it is stale

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const ROOT = path.resolve(import.meta.dir, "..")
export const KEYS_JSON = path.resolve(ROOT, "../../packages/shared/src/app-signing/keys.json")
export const PINNED_KEYS_SWIFT = path.join(
  ROOT,
  "ios/LiaisonShell/Sources/LiaisonShell/PinnedKeys.swift",
)

interface KeysFile {
  keys: Array<{ keyId: string; publicKey: string }>
  revocationFloor: Array<{ name: string; below?: string; versions?: string[] }>
}

const swiftString = (s: string): string => JSON.stringify(s)

export function renderPinnedKeys(file: KeysFile): string {
  const keys = file.keys
    .map((k) => `        (keyId: ${swiftString(k.keyId)}, publicKey: ${swiftString(k.publicKey)}),`)
    .join("\n")
  const floor = file.revocationFloor
    .map((e) => {
      const below = e.below === undefined ? "nil" : swiftString(e.below)
      const versions =
        e.versions === undefined ? "nil" : `[${e.versions.map(swiftString).join(", ")}]`
      return `        RevocationEntry(name: ${swiftString(e.name)}, below: ${below}, versions: ${versions}),`
    })
    .join("\n")
  return `// SPDX-License-Identifier: FSL-1.1-ALv2
//
// GENERATED by apps/mobile/scripts/gen-shell-keys.ts from
// packages/shared/src/app-signing/keys.json. Do not edit: change keys.json and
// run the script (apps/mobile/shell-keys.test.ts fails while they differ).

public enum PinnedKeys {
    static let raw: [(keyId: String, publicKey: String)] = [
${keys}
    ]

    /// The pinned app-signing keys a served shell's statement must be signed by.
    public static var keys: [PinnedKey] {
        raw.compactMap { PinnedKey(keyId: $0.keyId, base64: $0.publicKey) }
    }

    /// The revocation floor compiled into this release.
    public static let revocationFloor: [RevocationEntry] = [
${floor}
    ]
}
`
}

export function expectedPinnedKeys(): string {
  return renderPinnedKeys(JSON.parse(readFileSync(KEYS_JSON, "utf8")) as KeysFile)
}

if (import.meta.main) {
  const expected = expectedPinnedKeys()
  if (process.argv.includes("--check")) {
    const current = readFileSync(PINNED_KEYS_SWIFT, "utf8")
    if (current !== expected) {
      console.log(
        `${path.relative(ROOT, PINNED_KEYS_SWIFT)} is stale: run scripts/gen-shell-keys.ts`,
      )
      process.exit(1)
    }
  } else {
    writeFileSync(PINNED_KEYS_SWIFT, expected)
    console.log(`wrote ${path.relative(ROOT, PINNED_KEYS_SWIFT)}`)
  }
}
