/**
 * docs/reference/setup.md, rendered from the same definitions the client card,
 * the in-product agent and `liaison guide` read (connection-setup.ts,
 * server-setup.ts) and the shipped manifests. `bun run docs:gen` writes it and
 * the docs freshness check fails when it is stale, so the page cannot drift
 * from what the product shows. Pure: relative imports only, so the docs
 * generator can load it without the server env.
 */
import { type ConnectionDecl, connectionSetup, connectionSetupExtraSteps } from "./connection-setup"
import { serverSetup } from "./server-setup"
import {
  basicOnboardingSummary,
  CONNECTION_ESTIMATES,
  estimateTotals,
  fullOnboardingSummary,
  KNOWLEDGE_ESTIMATE,
  SERVER_ESTIMATES,
  TRIAL_SUMMARY,
} from "./setup-timings"

/** The example address the page computes its values for. */
export const REFERENCE_BASE_URL = "https://liaison.example.com"
const REFERENCE_ORG_ID = "<org-id>"

export interface ReferenceManifest {
  name: string
  manifest: Record<string, unknown>
}

function range([low, high]: [number, number]): string {
  return low === high ? `${low} min` : `${low} to ${high} min`
}

/** "**HUMAN** (2 min)" or "**AGENT**". */
function stepLabel(step: { who: "human" | "agent"; minutes?: number }): string {
  if (step.who === "agent") return "**AGENT**"
  return step.minutes ? `**HUMAN** (${step.minutes} min)` : "**HUMAN**"
}

function md(text: string): string {
  return text.replace(/\s*\n\s*/g, " ").trim()
}

export function renderSetupReference(manifests: ReferenceManifest[]): string {
  const out: string[] = [
    "---",
    'title: "Setup reference"',
    'description: "Every step of a full setup: the server, then every connection the shipped apps offer, with who does each step, the page it happens on and the values to copy."',
    "---",
    "",
    "Generated by `bun run docs:gen` from the definitions the client cards, the in-product agent and `liaison guide` read. Do not edit.",
    "",
    `Values are shown for a server at \`${REFERENCE_BASE_URL}\`. On your server, \`liaison guide server\` and \`liaison guide <app>/<connection>\` print them for your own address, and \`liaison setup state\` says which steps are left. **HUMAN** steps happen in a provider's console or a browser; **AGENT** steps are commands or \`deploy/.env\` edits a coding agent runs.`,
    "",
    "## How long it takes",
    "",
    `Measured on a live install with a coding agent running the AGENT steps: ${TRIAL_SUMMARY}; ${basicOnboardingSummary()}; ${fullOnboardingSummary()}. The table splits those totals: your own time for each part, in the provider's console with its exact instructions in hand (the basic parts add up to ${range(estimateTotals().basic)}, the full onboarding to ${range(estimateTotals().full)}; the parts marked *on top* are outside it: a system of your own, or an alternative to another part); each HUMAN step below says its own time, and \`liaison setup state\` adds up the parts that are left. The waits are the provider's, not yours, are never in a total, and some take days.`,
    "",
    "| Step | Your time | Provider waits |",
    "|---|---|---|",
    `| Company knowledge and agents (interview, gathering, review, load, test) | ${range(KNOWLEDGE_ESTIMATE.minutes)} of yours (the agent gathers meanwhile) | |`,
  ]
  for (const s of serverSetup({ BASE_URL: REFERENCE_BASE_URL })) {
    const e = SERVER_ESTIMATES[s.id]
    if (!e || e.minutes[1] === 0) continue
    out.push(`| ${s.title} | ${range(e.minutes)} | ${e.waits ?? ""} |`)
  }
  for (const e of CONNECTION_ESTIMATES)
    out.push(
      `| ${e.label}${e.part === "extra" ? " *(on top)*" : ""} | ${range(e.minutes)} | ${e.waits ?? ""} |`,
    )
  out.push("", "## The server", "")
  for (const s of serverSetup({ BASE_URL: REFERENCE_BASE_URL })) {
    out.push(`### ${s.title}${s.optional ? " (optional)" : ""}`, "")
    if (s.env.length) out.push(`Variables: ${s.env.map((e) => `\`${e}\``).join(", ")}.`, "")
    for (const [i, step] of s.steps.entries()) {
      out.push(`${i + 1}. ${stepLabel(step)} ${md(step.text)}`)
      if (step.url) out.push(`   Open: <${step.url}>`)
      for (const v of step.values ?? []) out.push(`   \`${v}\``)
    }
    out.push("", `Verify: ${md(s.verify)}`, "")
  }
  out.push("## Connections", "")
  for (const m of [...manifests].sort((a, b) => a.name.localeCompare(b.name))) {
    const conns = (m.manifest.connections ?? {}) as Record<string, ConnectionDecl>
    const names = Object.keys(conns).sort()
    if (names.length === 0) continue
    const webhookEndpoints = Object.keys((m.manifest.webhooks ?? {}) as Record<string, unknown>)
    out.push(`### ${m.name}`, "")
    for (const name of names) {
      const s = connectionSetup({
        baseUrl: REFERENCE_BASE_URL,
        orgId: REFERENCE_ORG_ID,
        app: m.name,
        connection: name,
        decl: conns[name] as ConnectionDecl,
        webhookEndpoints,
      })
      out.push(
        `#### ${m.name}/${name}${s.purpose ? `: ${s.purpose}` : ""}`,
        "",
        `${s.type === "oauth2" ? "Sign-in at the provider (OAuth)" : "Credentials"}${s.optional ? ", optional" : ""}. Steps on your server: \`${s.guideCommand}\`.`,
        "",
      )
      if (s.family !== "app") {
        out.push(
          s.family === "google"
            ? "The Google guide covers it: the client, the redirect URIs, the scopes and the APIs to turn on for every Google connection of the apps that are on."
            : s.family === "shopify"
              ? "The Shopify guide covers it: the Dev Dashboard app with this server's URLs, scopes and API version."
              : "The IMAP guide covers it: the provider's servers and app-password steps.",
          "",
        )
        continue
      }
      if (s.summary) out.push(md(s.summary), "")
      const steps = [...s.steps, ...connectionSetupExtraSteps(s, "cli")]
      for (const [i, step] of steps.entries()) {
        out.push(`${i + 1}. ${stepLabel(step)} ${md(step.text)}`)
        if (step.url) out.push(`   Open: <${step.url}>`)
        for (const v of step.values ?? []) out.push(`   \`${v}\``)
      }
      if (s.docsUrl) out.push("", `Provider docs: <${s.docsUrl}>`)
      out.push("")
    }
  }
  return `${out.join("\n").trimEnd()}\n`
}
