// Media-analysis E2E — LIVE Gemini + REAL ffmpeg/ffprobe.
//
// This is the ONLY stage that proves `analyze_media` works end-to-end with a
// real model and a real transcode. Unit/integration tests (media-analysis-tool
// .test.ts, media-normalize.test.ts) mock `@google/genai` and the ffmpeg spawn;
// here we invoke the REAL handler (`handleAnalyzeMedia` with
// `defaultMediaAnalysisToolDeps`) against REAL fixture bytes in REAL object
// storage, so:
//   real getObjectBuffer  →  real normalizeMedia (ffmpeg/ffprobe/heic-convert)
//                          →  real @google/genai generateContent
//
// Graceful degradation (a bare CI box must NOT hard-fail): `beforeAll` probes
// the environment and sets flags; EACH test body early-returns (skip-with-note)
// when a prerequisite is missing. We do NOT use a declaration-time
// `test.skipIf(!fixturesPresent)` — `fixturesPresent` is set in `beforeAll`, so
// at `it(...)` declaration time it is still the initial `false` and would skip
// EVERY test. The repo precedent for the early-return guard is
// `assist-proofread.scenario.test.ts:85-88`.
// ---------------------------------------------------------------------------
