/** A copy of the recorded hit's company with fictional overrides (another company, a ceased one,
 *  a public body), for tests that need more than the one recorded answer. */
export function registryResultWith(over: {
  siren: string
  nom_complet: string
  nom_raison_sociale?: string | null
  sigle?: string | null
  etat_administratif?: "A" | "C"
  nature_juridique?: string
  code_postal?: string
  libelle_commune?: string
}): Record<string, unknown> {
  const base = JSON.parse(JSON.stringify(REGISTRY_SEARCH_HIT.results[0])) as Record<string, unknown>
  const siege = base.siege as Record<string, unknown>
  siege.siret = `${over.siren}00011`
  if (over.code_postal) siege.code_postal = over.code_postal
  if (over.libelle_commune) siege.libelle_commune = over.libelle_commune
  return {
    ...base,
    siren: over.siren,
    nom_complet: over.nom_complet,
    nom_raison_sociale: over.nom_raison_sociale ?? over.nom_complet,
    sigle: over.sigle ?? null,
    etat_administratif: over.etat_administratif ?? "A",
    nature_juridique: over.nature_juridique ?? "5710",
    siege,
    matching_etablissements: [],
    dirigeants: [],
    tva: [],
  }
}

/** A 200 search answer carrying `results`, as the sandbox fetch bridge returns it. */
export function registryResponse(results: unknown[]): {
  status: number
  headers: Record<string, string>
  body: string
} {
  return {
    status: 200,
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      results,
      total_results: results.length,
      page: 1,
      per_page: 10,
      total_pages: results.length ? 1 : 0,
    }),
  }
}
