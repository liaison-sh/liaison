const SCHEMA_ROOT_REF = "#/"

export function loadSchema(file = SCHEMA_FILE): JsonSchema {
  return JSON.parse(readFileSync(file, "utf8")) as JsonSchema
}

function isSchema(v: Json | undefined): v is JsonSchema {
  return typeof v === "object" && v !== null && !Array.isArray(v)
}

function resolveRef(root: JsonSchema, ref: string): JsonSchema | null {
  if (!ref.startsWith(SCHEMA_ROOT_REF)) return null
  let cur: Json | undefined = root
  for (const seg of ref.slice(SCHEMA_ROOT_REF.length).split("/")) {
    if (!isSchema(cur)) return null
    cur = cur[seg]
  }
  return isSchema(cur) ? cur : null
}

function typeName(s: JsonSchema): string {
  if (Array.isArray(s.type)) return s.type.join(" or ")
  if (typeof s.type === "string") return s.type
  return "value"
}

function code(v: Json): string {
  return `\`${typeof v === "string" ? v : JSON.stringify(v)}\``
}

function constraintsOf(s: JsonSchema): string[] {
  const out: string[] = []
  if (s.const !== undefined) out.push(`= ${code(s.const)}`)
  if (Array.isArray(s.enum)) out.push(`one of ${s.enum.map(code).join(", ")}`)
  if (typeof s.pattern === "string") out.push(`pattern ${code(s.pattern)}`)
  if (typeof s.format === "string") out.push(`format ${s.format}`)
  // zod's int bounds (±MAX_SAFE_INTEGER) are not a real constraint: left out.
  const bound = (v: Json | undefined) =>
    typeof v === "number" && Math.abs(v) >= Number.MAX_SAFE_INTEGER ? undefined : v
  const range = (label: string, rawLo: Json | undefined, rawHi: Json | undefined) => {
    const lo = bound(rawLo)
    const hi = bound(rawHi)
    if (lo !== undefined && hi !== undefined) out.push(`${label} ${lo}..${hi}`)
    else if (lo !== undefined) out.push(`${label} ≥ ${lo}`)
    else if (hi !== undefined) out.push(`${label} ≤ ${hi}`)
  }
  range("length", s.minLength, s.maxLength)
  range("value", s.minimum, s.maximum)
  range("items", s.minItems, s.maxItems)
  if (s.default !== undefined) out.push(`default ${code(s.default)}`)
  if (isSchema(s.propertyNames) && typeof s.propertyNames.pattern === "string") {
    out.push(`keys match ${code(s.propertyNames.pattern)}`)
  }
  if (isSchema(s.propertyNames) && typeof s.propertyNames.maxLength === "number") {
    out.push(`keys ≤ ${s.propertyNames.maxLength} chars`)
  }
  return out
}

/** The `type` const shared by every variant of a discriminated union, or null. */
function discriminators(variants: JsonSchema[]): string[] | null {
  const names: string[] = []
  for (const v of variants) {
    const props = v.properties
    const t = isSchema(props) ? props.type : undefined
    if (!isSchema(t) || typeof t.const !== "string") return null
    names.push(t.const)
  }
  return names
}

export function schemaRows(root: JsonSchema): SchemaRow[] {
  const rows: SchemaRow[] = []
  const seenRefs = new Set<string>()

  function walk(raw: JsonSchema, path: string, required: boolean, emitSelf: boolean): void {
    let s = raw
    if (typeof s.$ref === "string") {
      const ref = s.$ref
      const target = resolveRef(root, ref)
      if (!target || seenRefs.has(ref)) {
        rows.push({ path, type: "template value (recursive)", required, constraints: [] })
        return
      }
      seenRefs.add(ref)
      walk(
        { ...target, ...Object.fromEntries(Object.entries(s).filter(([k]) => k !== "$ref")) },
        path,
        required,
        emitSelf,
      )
      seenRefs.delete(ref)
      return
    }
    const union = (
      Array.isArray(s.oneOf) ? s.oneOf : Array.isArray(s.anyOf) ? s.anyOf : null
    )?.filter(isSchema)
    if (union) {
      const names = discriminators(union)
      if (names) {
        if (emitSelf) {
          rows.push({
            path,
            type: "object",
            required,
            constraints: [`\`type\` one of ${names.map(code).join(", ")}`],
          })
        }
        union.forEach((variant, i) => {
          walk(variant, `${path}[type=${names[i]}]`, true, false)
        })
        return
      }
      // A non-discriminated union (the body template): one row naming the alternatives.
      rows.push({
        path,
        type: union.map((v) => (typeof v.$ref === "string" ? "template" : typeName(v))).join(" | "),
        required,
        constraints: union.flatMap((v) =>
          typeof v.$ref === "string" ? [] : constraintsOf(v).map((c) => `${typeName(v)}: ${c}`),
        ),
      })
      return
    }
    s = raw
    const type = typeName(s)
    if (emitSelf) rows.push({ path, type, required, constraints: constraintsOf(s) })
    if (type === "object") {
      const props = isSchema(s.properties) ? s.properties : null
      const req = new Set(
        Array.isArray(s.required) ? s.required.filter((r) => typeof r === "string") : [],
      )
      if (props) {
        for (const [key, sub] of Object.entries(props)) {
          if (!isSchema(sub)) continue
          // A variant's `type` discriminator is already in the parent row.
          if (key === "type" && typeof sub.const === "string" && path.endsWith("]")) continue
          walk(sub, path ? `${path}.${key}` : key, req.has(key), true)
        }
      }
      if (isSchema(s.additionalProperties)) {
        walk(s.additionalProperties, `${path}.<key>`, false, true)
      }
    } else if (type === "array" && isSchema(s.items)) {
      walk(s.items, `${path}[]`, true, true)
    }
  }

  walk(root, "", true, false)
  return rows
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\n/g, " ")
}

export function renderSchemaReference(root: JsonSchema): string {
  const rows = schemaRows(root)
  const lines = [
    "| Field | Type | Required | Constraints | Notes |",
    "|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| \`${cell(r.path)}\` | ${cell(r.type)} | ${r.required ? "yes" : "no"} | ${cell(r.constraints.join("; "))} | ${cell(FIELD_NOTES[r.path] ?? "")} |`,
    ),
  ]
  return `${lines.join("\n")}\n`
}

const list = (xs: readonly string[]): string =>
  xs.length ? xs.map((x) => `\`${x}\``).join(", ") : ""

export function renderRolesReference(registry: Record<string, RoleSpec> = ROLE_REGISTRY): string {
  const lines = [
    "| Role | What it answers | Params (all required) | Params (at least one) | Fields (must be allow-listed) |",
    "|---|---|---|---|---|",
    ...Object.entries(registry).map(
      ([name, spec]) =>
        `| \`${name}\` | ${cell(spec.description)} | ${list(spec.requiredParams)} | ${list(spec.oneOfParams)} | ${list(spec.requiredFields)} |`,
    ),
  ]
  return `${lines.join("\n")}\n`
}

/** The text between a marker pair (exclusive, with the newline after BEGIN stripped). */
export function extractGenerated(
  doc: string,
  begin = BEGIN_MARKER,
  end = END_MARKER,
): string | null {
  const start = doc.indexOf(begin)
  const stop = doc.indexOf(end)
  if (start < 0 || stop < 0 || stop < start) return null
  return doc.slice(start + begin.length + 1, stop)
}

export function replaceGenerated(
  doc: string,
  generated: string,
  begin = BEGIN_MARKER,
  end = END_MARKER,
): string {
  const start = doc.indexOf(begin)
  const stop = doc.indexOf(end)
  if (start < 0 || stop < 0 || stop < start) {
    throw new Error(`the document is missing the markers ${begin} / ${end}`)
  }
  return `${doc.slice(0, start + begin.length)}\n${generated}${doc.slice(stop)}`
}

/** The doc with both generated blocks brought up to date. */
export function regenerate(doc: string): string {
  const withSchema = replaceGenerated(doc, renderSchemaReference(loadSchema()))
  return replaceGenerated(withSchema, renderRolesReference(), ROLES_BEGIN_MARKER, ROLES_END_MARKER)
}

if (import.meta.main) {
  const mode = process.argv[2]
  if (mode !== "--write" && mode !== "--check") {
    console.error("usage: bun run scripts/api-connector-schema-doc.ts --write | --check")
    process.exit(2)
  }
  let stale = false
  for (const file of GENERATED_FILES) {
    const doc = readFileSync(file, "utf8")
    const next = regenerate(doc)
    if (mode === "--write") {
      if (next !== doc) writeFileSync(file, next)
      console.log(`updated ${file}`)
    } else if (next !== doc) {
      console.error(
        `${file}'s generated tables are stale: run bun run scripts/api-connector-schema-doc.ts --write`,
      )
      stale = true
    }
  }
  if (stale) process.exit(1)
  if (mode === "--check") console.log("the generated api-connector tables are current")
}
