/**
 * Real-DB + real object storage (SeaweedFS) test for `projects attach-files`
 * (cli/projects/attach-files.ts): historical files attached to tasks that
 * `projects import` created, as task-parented `kernel.files` rows.
 *
 * - happy path: one row per file on the task (app projects / entity task),
 *   backdated, uploaded_by the original uploader, ordinal = index in the
 *   record, deterministic id = storage-key segment, bytes in storage, listed
 *   by the task page's read (listFiles), one `file:create` event per file.
 * - idempotency per file: a re-run uploads nothing; a record with one new and
 *   one existing file stores only the new one.
 * - failures write nothing: missing task, path escapes (../, absolute,
 *   symlink, sibling prefix), size mismatch, org size limit, quota, blocked
 *   type, unknown author without the flag, bad records.
 * - placeholders, dry-run.
 * - silence: the queued events, run through the real attention translator,
 *   produce no attention row (so no push, no digest), and no message event.
 *
 * Fixtures: fictitious people at fabrikam.example / contoso.example and
 * generated bytes.
 */

