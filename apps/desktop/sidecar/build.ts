#!/usr/bin/env bun
// SPDX-License-Identifier: FSL-1.1-ALv2
//
// Compiles the sidecar to a standalone binary with `bun build --compile`.
// The output file name carries the target triple because that is what Tauri's
// `externalBin` resolution expects next to the base name it is given.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import path from "node:path"
import { ATELIER_VENDOR_DIR, vendoredAtelier } from "./atelier-bundle"
import {
  buildRootPrefixes,
  firstMatchContext,
  scanFile,
  scanFiles,
  subtractHits,
} from "./check-no-absolute-paths"

export const TARGETS = [
  "bun-darwin-arm64",
  "bun-darwin-x64",
  "bun-windows-x64",
  "bun-linux-x64",
] as const
export type Target = (typeof TARGETS)[number]

export const DIST = path.join(import.meta.dir, "dist")
/** Generated per-target entry modules. Never committed, rewritten every build. */
export const ENTRIES = path.join(import.meta.dir, ".entries")

/**
 * The SDK ships its Claude Code CLI as one optional package per platform, and
 * `require.resolve` does not work inside a compiled binary's `$bunfs`, so the
 * right platform's CLI is embedded as a file asset and extracted at startup.
 * A static import is the only way to embed one, and a static import cannot be
 * conditional, so the entry module is generated per target instead.
 */
const PLATFORM_CLI_PACKAGE: Record<Target, string> = {
  "bun-darwin-arm64": "@anthropic-ai/claude-agent-sdk-darwin-arm64",
  "bun-darwin-x64": "@anthropic-ai/claude-agent-sdk-darwin-x64",
  "bun-linux-x64": "@anthropic-ai/claude-agent-sdk-linux-x64",
  "bun-windows-x64": "@anthropic-ai/claude-agent-sdk-win32-x64",
}

/**
 * The CLI's file name inside its package. Windows ships `claude.exe`, and
 * that is what the package resolves; the SDK's extractor keeps the basename,
 * so the extracted file stays an `.exe` too. Resolving `claude` on every
 * platform found nothing on Windows, the build fell back to "the SDK
 * resolves its own", and the first Windows walk's local session died on its
 * first turn with "Native CLI binary for win32-x64 not found".
 */
export function platformCliFile(target: Target): string {
  return target === "bun-windows-x64" ? "claude.exe" : "claude"
}

/** The package specifier the entry module imports as a file asset. */
export function platformCliSpecifier(target: Target): string {
  return `${PLATFORM_CLI_PACKAGE[target]}/${platformCliFile(target)}`
}

/**
 * The platform CLI package for a target, or null when it is not installed.
 * npm and bun install only the packages matching the host, so a cross compile
 * on a developer machine legitimately has none of the other three; the build
 * says so out loud rather than quietly shipping the wrong platform's CLI.
 */
export function platformCliPackage(target: Target): string | null {
  try {
    Bun.resolveSync(platformCliSpecifier(target), import.meta.dir)
    return PLATFORM_CLI_PACKAGE[target]
  } catch {
    return null
  }
}

/**
 * A binary for the machine that builds it is the one that ships (CI compiles
 * the host triple only), and one without its CLI cannot run a single turn.
 * That used to be a warning on stderr, which a green workflow buried. Returns
 * the message such a build fails with, or null when it may go out.
 */
export function unshippableReason(
  target: Target,
  cliPackage: string | null,
  host: Target = hostTarget(),
): string | null {
  if (cliPackage || target !== host) return null
  return (
    `no Claude Code CLI embedded for ${target}, the machine's own triple: ` +
    `${platformCliSpecifier(target)} did not resolve. Install ` +
    `${PLATFORM_CLI_PACKAGE[target]} (a bun install without --omit=optional) before building a shippable binary`
  )
}

/** Generated per build from vendor/atelier/MANIFEST.json. Never committed. */
export const ATELIER_EMBED = path.join(import.meta.dir, "vendor", "atelier.embed.gen.ts")

/**
 * S38 (A33): every vendored Atelier file embedded as a file asset, the way the
 * CLI is, with its manifest hash; the entry registers it before main runs.
 */
export function writeAtelierEmbed(file: string = ATELIER_EMBED): string {
  const embed = vendoredAtelier()
  const rel = (f: string) => `./${path.relative(path.dirname(file), f).split(path.sep).join("/")}`
  const imports = embed.files.map(
    (f, i) => `import f${i} from ${JSON.stringify(rel(f.source))} with { type: "file" }\n`,
  )
  const rows = embed.files.map(
    (f, i) =>
      `    { path: ${JSON.stringify(f.path)}, source: f${i}, sha256: ${JSON.stringify(f.sha256)} },\n`,
  )
  writeIfChanged(
    file,
    `// SPDX-License-Identifier: FSL-1.1-ALv2\n` +
      `// Generated by build.ts from ${path.basename(ATELIER_VENDOR_DIR)}/MANIFEST.json. Do not edit.\n` +
      `import type { AtelierEmbed } from "../atelier-bundle"\n` +
      imports.join("") +
      `export const ATELIER: AtelierEmbed = {\n` +
      `  version: ${JSON.stringify(embed.version)},\n` +
      `  commit: ${JSON.stringify(embed.commit)},\n` +
      `  files: [\n${rows.join("")}  ],\n}\n`,
  )
  return file
}

/**
 * Writes `content` only when the file does not already hold it. The universal
 * macOS build compiles two slices in turn and stamps the first before the
 * second regenerates this module; a rewrite with the same bytes still bumps the
 * mtime, and build.rs's freshness check (sidecar_freshness.rs, mtime based)
 * then refused the first slice's stamp (W1-D1).
 */
export function writeIfChanged(file: string, content: string): boolean {
  try {
    if (readFileSync(file, "utf8") === content) return false
  } catch {
    // absent or unreadable: written below
  }
  writeFileSync(file, content)
  return true
}

export function writeEntry(target: Target): string {
  mkdirSync(ENTRIES, { recursive: true })
  writeAtelierEmbed()
  const name = platformCliPackage(target)
  const file = path.join(ENTRIES, `entry-${target}.ts`)
  // S38: the bundled Atelier's files, embedded and registered before main.
  const atelier =
    `import { ATELIER } from "../vendor/atelier.embed.gen"\n` +
    `import { registerEmbeddedAtelier } from "../atelier-bundle"\n` +
    `registerEmbeddedAtelier(ATELIER)\n`
  const source = name
    ? `// Generated by build.ts. Do not edit.\n` +
      atelier +
      `import cli from "${platformCliSpecifier(target)}" with { type: "file" }\n` +
      `import { extractFromBunfs } from "@anthropic-ai/claude-agent-sdk/extract"\n` +
      `import { main } from "../index"\n` +
      `import { headersHelperConfigPath } from "../mcp-token"\n` +
      `import { isBrowserSinkCall, isWatchdogCall } from "../claude-auth"\n` +
      // The headers helper (mcp-token.ts) runs this binary on every MCP
      // connect, and the Claude sign-in's browser sink and watchdog
      // (claude-auth.ts) once per sign-in; none of them spawns the CLI, so none
      // pays for reading and hashing the whole embedded CLI first.
      `const helper = headersHelperConfigPath(process.argv.slice(2)) !== null ||\n` +
      `  isBrowserSinkCall(process.argv.slice(2)) || isWatchdogCall(process.argv.slice(2))\n` +
      `process.exit(await main(helper ? null : extractFromBunfs(cli)))\n`
    : `// Generated by build.ts. Do not edit.\n` +
      `// No platform CLI package installed for ${target}: the SDK resolves its own.\n` +
      atelier +
      `import { main } from "../index"\n` +
      `process.exit(await main(null))\n`
  writeIfChanged(file, source)
  return file
}

/** The triple this machine compiles for when it compiles for itself. */
export function hostTarget(): Target {
  const os =
    process.platform === "darwin" ? "darwin" : process.platform === "win32" ? "windows" : "linux"
  const arch = process.arch === "arm64" ? "arm64" : "x64"
  const guess = `bun-${os}-${arch}`
  return isTarget(guess) ? guess : "bun-darwin-arm64"
}

/** Where `bun build --compile` keeps the runtimes it downloads for a target it
 *  is not running on. Read from the environment like bun itself reads it. */
function bunCacheDir(): string {
  const explicit = process.env.BUN_INSTALL_CACHE_DIR
  if (explicit) return explicit
  return path.join(process.env.BUN_INSTALL ?? path.join(homedir(), ".bun"), "install", "cache")
}

/** The Bun runtime a target's binary is built on top of: the cached download
 *  for this bun version, and for the host triple the executable running this
 *  build, which is what the compile appends to. Null when neither is there. */
export function bunRuntimeFor(target: Target): string | null {
  const cache = bunCacheDir()
  const exact = path.join(cache, `${target}-v${Bun.version}`)
  if (existsSync(exact)) return exact
  if (target === hostTarget()) return process.execPath
  try {
    const versioned = readdirSync(cache)
      .filter((name) => name.startsWith(`${target}-v`))
      .sort()
    const newest = versioned.at(-1)
    return newest ? path.join(cache, newest) : null
  } catch {
    return null
  }
}

/**
 * The files copied into a target's binary verbatim, which this build did not
 * produce and cannot rebuild: the Bun runtime and, when it is installed, the
 * platform's Claude Code CLI. Both were themselves compiled on a CI runner, so
 * both carry that runner's home directory, and on a GitHub runner that is the
 * very prefix the path check refuses. Measuring what they contribute is what
 * keeps the check exact instead of either blind or permanently red.
 */
export function vendoredPayloads(target: Target): string[] {
  const files: string[] = []
  const runtime = bunRuntimeFor(target)
  if (runtime) files.push(runtime)
  if (platformCliPackage(target)) {
    files.push(Bun.resolveSync(platformCliSpecifier(target), import.meta.dir))
  }
  return files
}

export function outfileFor(target: Target): string {
  const suffix = target === "bun-windows-x64" ? ".exe" : ""
  return path.join(DIST, `liaison-sidecar-${target}${suffix}`)
}

export function buildOne(target: Target): string {
  const outfile = outfileFor(target)
  // Decided before the compile, which is the expensive part of a build that
  // was never going to ship.
  const cliPackage = platformCliPackage(target)
  const unshippable = unshippableReason(target, cliPackage)
  if (unshippable) throw new Error(unshippable)
  const result = Bun.spawnSync(
    ["bun", "build", "--compile", `--target=${target}`, writeEntry(target), "--outfile", outfile],
    { cwd: import.meta.dir, stdout: "inherit", stderr: "inherit" },
  )
  if (result.exitCode !== 0) throw new Error(`compile failed for ${target}`)
  if (!cliPackage) {
    process.stderr.write(
      `warning: no Claude Code CLI embedded in ${path.basename(outfile)}: install ` +
        `${PLATFORM_CLI_PACKAGE[target]} on the build machine for a shippable ${target} binary\n`,
    )
  }
  // A build machine path baked into the binary is only visible if something
  // looks, so the compile step looks every time rather than leaving it to a
  // check somebody remembers to run. What the vendored payloads brought with
  // them is subtracted first: on a GitHub runner the Bun runtime and the
  // embedded CLI are full of the runner's own home directory, and blaming this
  // build for those fails every CI job while catching nothing.
  const prefixes = buildRootPrefixes(process.env)
  const raw = scanFile(outfile, prefixes)
  if (raw.length > 0) {
    const payloads = vendoredPayloads(target)
    const hits = subtractHits(raw, scanFiles(payloads, prefixes))
    if (hits.length > 0) {
      const detail = hits
        .map((hit) => {
          const context = firstMatchContext(outfile, hit.prefix)
          return (
            `${hit.prefix} (${hit.name}, ${hit.count} reference(s) beyond the ` +
            `vendored payloads, ${hit.encodings.join(" and ")})` +
            (context === null ? "" : `\n  first occurrence: ${context}`)
          )
        })
        .join("\n")
      throw new Error(
        `build root path is baked into ${path.basename(outfile)}:\n${detail}\n` +
          `vendored payloads measured: ${payloads.length === 0 ? "none found" : payloads.join(", ")}`,
      )
    }
  }
  return outfile
}

/** Compile every shipping triple. Returns each output path. */
export function buildAll(): string[] {
  return TARGETS.map((target) => buildOne(target))
}

function isTarget(value: string): value is Target {
  return (TARGETS as readonly string[]).includes(value)
}

if (import.meta.main) {
  const argv = process.argv.slice(2)
  const index = argv.indexOf("--target")
  if (index === -1) {
    buildAll()
  } else {
    const requested = argv[index + 1]
    if (!requested || !isTarget(requested)) {
      process.stderr.write(`usage: bun run build.ts [--target <${TARGETS.join("|")}>]\n`)
      process.exit(2)
    }
    buildOne(requested)
  }
}
