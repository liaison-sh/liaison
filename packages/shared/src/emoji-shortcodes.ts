/** The emoji for an exact shortcode name (no colons), or undefined. */
export function emojiForShortcode(name: string): string | undefined {
  return Object.hasOwn(EMOJI_SHORTCODES, name) ? EMOJI_SHORTCODES[name] : undefined
}

export interface EmojiSuggestion {
  name: string
  emoji: string
}

/**
 * Shortcodes matching what was typed after the `:`, best first: an exact name,
 * then names starting with it (shorter first), then names containing it. The
 * aliases of one emoji (`thumbsup`, `+1`) collapse to the best-ranked one.
 */
export function searchEmojiShortcodes(query: string, limit = 8): EmojiSuggestion[] {
  const q = query.toLowerCase()
  if (!q) return []
  const ranked: Array<{ name: string; emoji: string; rank: number }> = []
  for (const [name, emoji] of Object.entries(EMOJI_SHORTCODES)) {
    const at = name.indexOf(q)
    if (at < 0) continue
    ranked.push({ name, emoji, rank: name === q ? 0 : at === 0 ? 1 : 2 })
  }
  ranked.sort(
    (a, b) => a.rank - b.rank || a.name.length - b.name.length || (a.name < b.name ? -1 : 1),
  )
  const seen = new Set<string>()
  const out: EmojiSuggestion[] = []
  for (const { name, emoji } of ranked) {
    if (seen.has(emoji)) continue
    seen.add(emoji)
    out.push({ name, emoji })
    if (out.length >= limit) break
  }
  return out
}
