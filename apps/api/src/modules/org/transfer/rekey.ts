//
// Stored secrets on a move: no ciphertext under an instance key leaves its
// instance.
//
// NOT A CRYPTO CHANGE. Both directions call `cli/keys-rotate.ts` unchanged:
//   export  every value of `COLUMNS` and every encrypted-looking string of
//           `JSON_COLUMNS` (both key families) goes through `rekeyValue`, from
//           the instance key to the family's one-time transfer key, under the
//           same context `liaison keys rotate` uses;
//   import  the rows land with transfer-key ciphertexts, then
//           `rotateEncryptionKey({ family, fromKey: transfer, toKey: own,
//           onlyOrgIds: [org], execute: true })` runs once per family while the
//           org is still `incoming` (serves nothing).
// The JSON walk below follows `rekeyJson` in keys-rotate.ts (same shape test,
// same family-per-path rule); keys-rotate.test.ts pins the column lists
// against `CryptoContext`, and transfer.test.ts pins this file's use of them.
//
// The transfer keys: one per family, 64 hex characters (the rotation's own
// check), generated by the exporting side, handed to the import on the first
// line of its input, held in memory only. They add nothing over the channel
// that carries the bundle; they exist so the target never needs the source's
// keys and the source never sees the target's.
import { randomBytes } from "node:crypto"
import {
  COLUMNS,
  JSON_COLUMNS,
  JSON_CONTEXTS,
  type KeyFamily,
  looksEncrypted,
  rekeyValue,
} from "~/cli/keys-rotate"

export type FamilyKeys = Record<KeyFamily, string | undefined>
export type TransferKeys = Record<KeyFamily, string>

export const KEY_FAMILIES: readonly KeyFamily[] = ["encryption", "byok"]

export function generateTransferKeys(): TransferKeys {
  return {
    encryption: randomBytes(32).toString("hex"),
    byok: randomBytes(32).toString("hex"),
  }
}

const HEX_KEY = /^[0-9a-f]{64}$/i

/** Parse the first input line (`{"encryption":"<hex>","byok":"<hex>"}`). */
export function parseTransferKeys(line: string): TransferKeys {
  let v: unknown
  try {
    v = JSON.parse(line)
  } catch {
    throw new Error("org transfer: the first input line must hold the transfer keys (JSON)")
  }
  const o = v as Partial<TransferKeys>
  if (!o || !HEX_KEY.test(o.encryption ?? "") || !HEX_KEY.test(o.byok ?? "")) {
    throw new Error("org transfer: the transfer keys must be two 64-hex values (encryption, byok)")
  }
  return { encryption: o.encryption as string, byok: o.byok as string }
}

export class RekeyRefused extends Error {
  constructor(where: string, status: string) {
    super(
      `org transfer: a stored secret in ${where} does not open with this instance's key (${status}); ` +
        "nothing is exported",
    )
    this.name = "RekeyRefused"
  }
}

export interface RekeyTally {
  encryption: number
  byok: number
}

/** The encrypted places of one table, per keys-rotate's lists. */
export function encryptedPlaces(table: string): {
  columns: typeof COLUMNS
  json: typeof JSON_COLUMNS
} {
  return {
    columns: COLUMNS.filter((c) => `${c.schema}.${c.table}` === table),
    json: JSON_COLUMNS.filter((c) => `${c.schema}.${c.table}` === table),
  }
}

function rekeyOne(
  value: string,
  contexts: string[],
  family: KeyFamily,
  from: FamilyKeys,
  to: TransferKeys,
  where: string,
): string {
  const fromKey = from[family]
  if (!fromKey) throw new RekeyRefused(where, `no ${family} key on this instance`)
  const r = rekeyValue(value, contexts, fromKey, to[family])
  if (r.status !== "rekeyed") throw new RekeyRefused(where, r.status)
  return r.value
}

function walk(
  node: unknown,
  path: string[],
  familyAt: (path: readonly string[]) => KeyFamily,
  from: FamilyKeys,
  to: TransferKeys,
  where: string,
  tally: RekeyTally,
): unknown {
  if (typeof node === "string") {
    if (!looksEncrypted(node)) return node
    const family = familyAt(path)
    tally[family] += 1
    return rekeyOne(node, JSON_CONTEXTS[family], family, from, to, where)
  }
  if (Array.isArray(node)) {
    return node.map((n, i) => walk(n, [...path, String(i)], familyAt, from, to, where, tally))
  }
  if (node && typeof node === "object") {
    const out: Record<string, unknown> = {}
    for (const [k, v] of Object.entries(node)) {
      out[k] = walk(v, [...path, k], familyAt, from, to, where, tally)
    }
    return out
  }
  return node
}

/**
 * Re-key one exported row (its `to_jsonb` object) of `table` in place: instance
 * keys to transfer keys. Throws `RekeyRefused` for a value that does not open.
 */
export function rekeyRowForExport(
  table: string,
  row: Record<string, unknown>,
  from: FamilyKeys,
  to: TransferKeys,
  tally: RekeyTally,
): void {
  const places = encryptedPlaces(table)
  // The refusal names the row, so the one stale value can be found and fixed.
  const ref = typeof row.id === "string" || typeof row.id === "number" ? ` (row ${row.id})` : ""
  for (const col of places.columns) {
    const v = row[col.column]
    if (typeof v !== "string" || v === "") continue
    const context = col.rowContext
      ? col.rowContext.build(
          Object.fromEntries(col.rowContext.columns.map((c) => [c, String(row[c] ?? "")])),
        )
      : col.context
    tally[col.family] += 1
    row[col.column] = rekeyOne(v, [context], col.family, from, to, `${table}.${col.column}${ref}`)
  }
  for (const col of places.json) {
    const v = row[col.column]
    if (v === null || v === undefined) continue
    // A jsonb column arrives as its JSON value (to_jsonb), never as text.
    row[col.column] = walk(v, [], col.familyAt, from, to, `${table}.${col.column}${ref}`, tally)
  }
}
