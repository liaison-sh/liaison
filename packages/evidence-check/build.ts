// Bundle the checker page's script (src/page/main.ts with asn1js, the signing
// module's canonical JSON and constants, and the pure-JS SHA-256) into one
// string module (base64), src/generated/page-script.ts, with the SHA-256 the page's
// content security policy allows it by. `bun run build` writes it;
// `evidence-check.test.ts` rebuilds it and fails when the committed file is stale.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import type { BunPlugin } from "bun"

const HERE = import.meta.dir
export const GENERATED = path.join(HERE, "src/generated/page-script.ts")

/**
 * Resolve the page's dependencies to their ES module builds (`module`), so the
 * bundle is the same whichever directory or runner builds it: without this,
 * Bun picks `main` (CommonJS) in some runs and `module` in others.
 */
const esModuleBuilds: BunPlugin = {
  name: "es-module-builds",
  setup(build) {
    build.onResolve({ filter: /^(?:asn1js|pvtsutils|pvutils|tslib)$/ }, (args) => {
      const pkgJson = Bun.resolveSync(`${args.path}/package.json`, args.resolveDir)
      const pkg = JSON.parse(readFileSync(pkgJson, "utf8")) as { module?: string; main?: string }
      const entry = pkg.module ?? pkg.main
      if (!entry) throw new Error(`${args.path} names no entry file`)
      return { path: path.join(path.dirname(pkgJson), entry) }
    })
  },
}

export async function bundlePageScript(): Promise<string> {
  const out = await Bun.build({
    entrypoints: [path.join(HERE, "src/page/main.ts")],
    target: "browser",
    format: "iife",
    minify: true,
    // The same bytes whatever the build environment (a test run sets NODE_ENV).
    define: { "process.env.NODE_ENV": JSON.stringify("production") },
    env: "disable",
    plugins: [esModuleBuilds],
  })
  if (!out.success || out.outputs.length !== 1) {
    throw new Error(`page bundle failed: ${out.logs.map(String).join("\n")}`)
  }
  const script = (await out.outputs[0]!.text()).trim()
  // The script is inlined in a <script> element: it must never close it.
  if (/<\/script/i.test(script) || /<!--/.test(script)) {
    throw new Error("the page bundle holds a sequence that would end its script element")
  }
  return script
}

export function generatedSource(script: string): string {
  const hash = createHash("sha256").update(script, "utf8").digest("base64")
  return [
    "// SPDX-License-Identifier: FSL-1.1-ALv2",
    "// Generated by packages/evidence-check/build.ts from src/page/. Do not edit.",
    `export const PAGE_SCRIPT_SHA256_BASE64 = ${JSON.stringify(hash)}`,
    "// The script as base64 (UTF-8), so the file holds no quote or placeholder a formatter rewrites.",
    "export const PAGE_SCRIPT_BASE64 =",
    `  "${Buffer.from(script, "utf8").toString("base64")}"`,
    "",
  ].join("\n")
}

if (import.meta.main) {
  const next = generatedSource(await bundlePageScript())
  const prev = (() => {
    try {
      return readFileSync(GENERATED, "utf8")
    } catch {
      return ""
    }
  })()
  if (prev !== next) writeFileSync(GENERATED, next)
  console.log(`${prev === next ? "unchanged" : "wrote"} ${path.relative(process.cwd(), GENERATED)}`)
}
