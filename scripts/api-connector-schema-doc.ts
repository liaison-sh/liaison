export const DOC_FILE = join(ROOT, "docs/api-connector.md")
export const REFERENCE_FILE = join(ROOT, "apps/api/src/apps/api-connector/reference/authoring.md")
/** Every file carrying the generated blocks. */
export const GENERATED_FILES = [DOC_FILE, REFERENCE_FILE]
export const BEGIN_MARKER =
  "<!-- api-connector-schema:begin (generated by scripts/api-connector-schema-doc.ts; do not edit) -->"
export const END_MARKER = "<!-- api-connector-schema:end -->"
export const ROLES_BEGIN_MARKER =
  "<!-- api-connector-roles:begin (generated by scripts/api-connector-schema-doc.ts; do not edit) -->"
export const ROLES_END_MARKER = "<!-- api-connector-roles:end -->"

type Json = null | boolean | number | string | Json[] | { [key: string]: Json }
export type JsonSchema = { [key: string]: Json }

export interface SchemaRow {
  path: string
  type: string
  required: boolean
  constraints: string[]
}

