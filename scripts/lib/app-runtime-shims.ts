//
// The host exposes ONE Solid runtime to plugin-app UI bundles: `apps/web`
// assigns the real `solid-js{,/web,/store}` module namespaces onto window
// globals, `apps/web/index.html` declares an import map pointing the three bare
// specifiers at shim files under `apps/web/public/_app-runtime/`, and each shim
// re-exports the global's members.
//
// ESM named exports are static, so those shims carry a LITERAL export list. A
// hand-maintained list silently rots: the day a bundled app's compiled output
// starts importing a symbol the shim never listed (`setStyleProperty`, emitted
// by Solid's JSX transform for dynamic `style` props), the browser refuses the
// module with "does not provide an export named ..." and the whole app UI fails
// to load — at runtime, on the deployed box, with every test green.
//
// This module is the single source of truth for the shim contract:
//   - `renderShim` GENERATES a shim from a module's real export list, so the
//     list can never be shorter than the runtime's.
//   - `findUnsupportedBundleImports` CHECKS a built `ui.js` against the shims,
//     so freeze fails on the build machine instead of the browser.
import { readFileSync } from "node:fs"
import { join } from "node:path"

/** The three specifiers the freeze bundler externalizes, and their shims. */
export const SHIM_SPECIFIERS = ["solid-js", "solid-js/web", "solid-js/store"] as const
export type ShimSpecifier = (typeof SHIM_SPECIFIERS)[number]

interface ShimDescriptor {
  /** Filename under `apps/web/public/_app-runtime/`. */
  file: string
  /** The window global `apps/web/src/index.tsx` assigns the namespace to. */
  global: string
  /** Sub-path imported from the installed `solid-js` package, for export discovery. */
  modulePath: string
}

export const SHIMS: Record<ShimSpecifier, ShimDescriptor> = {
  "solid-js": {
    file: "solid-js.js",
    global: "__liaisonSolid",
    modulePath: "dist/solid.js",
  },
  "solid-js/web": {
    file: "solid-js-web.js",
    global: "__liaisonSolidWeb",
    modulePath: "web/dist/web.js",
  },
  "solid-js/store": {
    file: "solid-js-store.js",
    global: "__liaisonSolidStore",
    modulePath: "store/dist/store.js",
  },
}

export const SHIM_DIR = join("apps", "web", "public", "_app-runtime")

export function shimPath(repoRoot: string, specifier: ShimSpecifier): string {
  return join(repoRoot, SHIM_DIR, SHIMS[specifier].file)
}

/** Where the HOST's own copy of solid-js lives (the one `apps/web` bundles). */
export function hostSolidModulePath(repoRoot: string, specifier: ShimSpecifier): string {
  return join(repoRoot, "apps", "web", "node_modules", "solid-js", SHIMS[specifier].modulePath)
}

/**
 * Every export name the host's real module provides. Read by importing it —
 * the runtime namespace is the contract the browser enforces, not the .d.ts.
 */
export async function readHostModuleExports(
  repoRoot: string,
  specifier: ShimSpecifier,
): Promise<string[]> {
  const mod = (await import(hostSolidModulePath(repoRoot, specifier))) as Record<string, unknown>
  return Object.keys(mod)
    .filter((name) => name !== "default" && /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name))
    .sort()
}

/** The export names a shim file actually declares. */
export function readShimExports(repoRoot: string, specifier: ShimSpecifier): string[] {
  const source = readFileSync(shimPath(repoRoot, specifier), "utf8")
  return parseShimExports(source)
}

export function parseShimExports(source: string): string[] {
  const names: string[] = []
  const re = /^export\s+const\s+([A-Za-z_$][A-Za-z0-9_$]*)\s*=/gm
  let match = re.exec(source)
  while (match) {
    names.push(match[1])
    match = re.exec(source)
  }
  return names
}

/** Export names that collide with a JS global, so the generator pre-silences biome. */
const RESTRICTED_GLOBALS = new Set(["escape", "unescape", "eval", "undefined", "NaN", "Infinity"])

const HEADER = `// SPDX-License-Identifier: FSL-1.1-ALv2
// GENERATED by scripts/gen-app-runtime-shims.ts -- do not edit by hand.
// Run \`bun run scripts/gen-app-runtime-shims.ts\` after changing the solid-js
// version. The export list mirrors the host runtime's own namespace so a plugin
// bundle can never import a symbol this shim omits.
//
// The kernel frontend's index.html declares an import map that resolves bare`

export function renderShim(specifier: ShimSpecifier, exportNames: string[]): string {
  const { global } = SHIMS[specifier]
  const lines = [
    HEADER,
    `// "${specifier}" specifiers (used by plugin-app UI bundles) to this file. We`,
    `// re-export from window.${global}, which the kernel sets at startup`,
    `// (apps/web/src/index.tsx). Result: kernel + plugin share exactly one`,
    "// reactive graph and one Solid copy.",
    `const m = window.${global}`,
    "if (!m) {",
    "  throw new Error(",
    `    "${specifier} shim: window.${global} was not set by the kernel before the plugin bundle loaded",`,
    "  )",
    "}",
    ...exportNames.flatMap((name) =>
      RESTRICTED_GLOBALS.has(name)
        ? [
            `// biome-ignore lint/suspicious/noShadowRestrictedNames: re-export of the host runtime's own export name`,
            `export const ${name} = m.${name}`,
          ]
        : [`export const ${name} = m.${name}`],
    ),
    "export default m.default ?? m",
  ]
  return `${lines.join("\n")}\n`
}

export interface BundleImport {
  specifier: string
  /** The name imported FROM the module (before any `as` alias). */
  imported: string
}

/**
 * Named imports a built ESM bundle takes from the shimmed specifiers.
 * esbuild emits one `import { x as _$x } from "solid-js/web";` per symbol, but
 * multi-specifier and namespace forms are handled too.
 */
export function parseBundleSolidImports(code: string): BundleImport[] {
  const out: BundleImport[] = []
  const re = /import\s*(\{[^}]*\}|\*\s+as\s+[A-Za-z_$][\w$]*)\s*from\s*["']([^"']+)["']/g
  let match = re.exec(code)
  while (match) {
    const [, clause, specifier] = match
    if ((SHIM_SPECIFIERS as readonly string[]).includes(specifier)) {
      if (clause.startsWith("{")) {
        for (const raw of clause.slice(1, -1).split(",")) {
          const name = raw
            .trim()
            .split(/\s+as\s+/)[0]
            .trim()
          if (name) out.push({ specifier, imported: name })
        }
      }
      // A `* as ns` import needs no per-symbol guarantee: property access on the
      // namespace is dynamic and cannot fail at module-evaluation time.
    }
    match = re.exec(code)
  }
  return out
}

/**
 * Symbols a built bundle imports that the host shims do not export. A non-empty
 * result means this bundle WILL fail to load in the browser.
 */
export function findUnsupportedBundleImports(
  code: string,
  shimExports: Record<string, string[]>,
): BundleImport[] {
  const seen = new Set<string>()
  const bad: BundleImport[] = []
  for (const entry of parseBundleSolidImports(code)) {
    const available = shimExports[entry.specifier]
    if (!available) continue
    if (available.includes(entry.imported)) continue
    const key = `${entry.specifier}#${entry.imported}`
    if (seen.has(key)) continue
    seen.add(key)
    bad.push(entry)
  }
  return bad
}

/** Read all three shims' export lists, keyed by specifier. */
export function readAllShimExports(repoRoot: string): Record<string, string[]> {
  const out: Record<string, string[]> = {}
  for (const specifier of SHIM_SPECIFIERS) {
    out[specifier] = readShimExports(repoRoot, specifier)
  }
  return out
}
