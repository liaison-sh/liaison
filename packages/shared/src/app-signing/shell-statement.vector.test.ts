// THE CROSS-LANGUAGE VECTOR for shell statements and shell floors.
//
// The desktop shell verifies shell statements in Rust
// (apps/desktop/src-tauri/src/served_shell.rs), against the same canonical
// JSON, key ids and revocation format this package defines. This test signs a
// statement and a revocation list with a FIXED test key (Ed25519 signatures
// are deterministic) and checks that the committed vector,
// shell-statement.vector.json, is exactly what this side produces. The Rust
// tests read the same file and verify it, so a change of canonical form, key
// id rule or floor comparison on either side fails one of the two.
//
// The key is a test key derived from a constant seed; it is not, and never
// becomes, a pinned key (keys.json).
import { describe, expect, it } from "bun:test"
import { createPrivateKey, createPublicKey, sign } from "node:crypto"
import { bytesToBase64, sha256Hex, utf8 } from "./encoding"
import { parseRevocationList, type RevocationList, revocationBytes } from "./revocations"
import {
  parseShellStatement,
  type ShellStatement,
  shellRevocationFor,
  shellStatementBytes,
  verifyShellStatement,
} from "./shell-statement"
import vector from "./shell-statement.vector.json"

/** PKCS#8 DER of an Ed25519 private key is this prefix and the 32-byte seed. */
const PKCS8_PREFIX = "302e020100300506032b657004220420"
const SEED = "07".repeat(32)

function testKey() {
  const privateKey = createPrivateKey({
    key: Buffer.from(PKCS8_PREFIX + SEED, "hex"),
    format: "der",
    type: "pkcs8",
  })
  const spki = createPublicKey(privateKey).export({ format: "der", type: "spki" })
  // The raw key is the last 32 bytes of the SPKI DER.
  const raw = new Uint8Array(spki.subarray(spki.length - 32))
  return {
    publicKey: bytesToBase64(raw),
    sign: (bytes: Uint8Array) => bytesToBase64(new Uint8Array(sign(null, bytes, privateKey))),
  }
}

const FILES: Record<string, string> = {
  "index.html": '<!doctype html><script>console.log("vector")</script>',
  "assets/app.js": "export const vector = 1\n",
}

async function build() {
  const key = testKey()
  const raw = Uint8Array.from(Buffer.from(key.publicKey, "base64"))
  const keyId = `app-${(await sha256Hex(raw)).slice(0, 16)}`
  const files: Record<string, string> = {}
  for (const [path, body] of Object.entries(FILES)) files[path] = await sha256Hex(utf8.encode(body))
  const statement: ShellStatement = {
    v: 1,
    kind: "shell",
    keyId,
    mode: "desktop",
    buildId: "0123456789abcdef",
    commit: "a".repeat(40),
    // 9 digits, below a 10-digit floor: as text "999999999" sorts AFTER
    // "1000000000", so a floor compared as a string would let it through.
    seq: 999_999_999,
    liaisonVersion: "nightly-20261128",
    bridge: { desktop: "^1", ios: "^1", android: "^1" },
    settingsSchema: 1,
    files,
    issuedAt: "2026-11-28T00:00:00.000Z",
  }
  const statementText = utf8.decode(shellStatementBytes(statement))
  const list: RevocationList = {
    v: 1,
    seq: 7,
    issuedAt: "2026-11-28T00:00:00.000Z",
    entries: [
      { name: "invoicing", below: "0.2.0" },
      { name: "shell:desktop", below: "1000000000" },
    ],
  }
  const listText = utf8.decode(revocationBytes(list))
  return {
    note: "Generated by shell-statement.vector.test.ts with a constant TEST seed; verified by apps/desktop/src-tauri/src/served_shell.rs. Never a pinned key.",
    key: { keyId, publicKey: key.publicKey },
    files: FILES,
    statement: statementText,
    statementSig: key.sign(utf8.encode(statementText)),
    revocations: listText,
    revocationsSig: key.sign(utf8.encode(listText)),
  }
}

describe("the shell statement cross-language vector", () => {
  it("is exactly what this side signs", async () => {
    expect(vector).toEqual(await build())
  })

  it("verifies here, and its seq is below the 10-digit floor numerically", async () => {
    const keys = [vector.key]
    const statementBytes = utf8.encode(vector.statement)
    const ok = await verifyShellStatement(statementBytes, vector.statementSig, keys, {
      list: null,
      floor: [],
    })
    expect(ok.ok).toBe(true)
    const parsed = parseShellStatement(statementBytes)
    const list = parseRevocationList(utf8.encode(vector.revocations))
    expect(parsed).not.toBeNull()
    expect(list).not.toBeNull()
    if (!parsed || !list) return
    expect(shellRevocationFor("desktop", parsed.seq, { list, floor: [] })).toBe("revoked")
  })
})
