// 5 up from apps/api/src/tests/e2e/ → the repository root (the established
// pattern, e.g. longtail.scenario.test.ts). The fixtures live at
// `<root>/qa/media-fixtures/` (synthetic, regenerated by its generate.sh);
// LIAISON_MEDIA_FIXTURES_DIR points the suite at another set with the same
// manifest ids.
const liaisonRoot = join(import.meta.dir, "..", "..", "..", "..", "..")
const fixturesDir =
  process.env.LIAISON_MEDIA_FIXTURES_DIR ?? join(liaisonRoot, "qa", "media-fixtures")
const manifestPath = join(fixturesDir, "manifest.json")

// Deterministic ids so teardown can clean up even on a mid-run crash.
const ORG_ID = "00000000-0000-4000-8000-00000000e2e1"
const USER_ID = "00000000-0000-4000-8000-00000000e2e2"
const MESSAGE_ID = "msg-media-e2e"

// Dedicated test-bookkeeping connection (NOT the app's `~/db` pool). The app
// pool's `idle_timeout: 20` closes an idle connection after 20s — and this
// suite's bookkeeping queries straddle multi-second LIVE Gemini calls (the longest
// video + a 3-attempt transient-retry sequence can leave the connection idle
// past 20s), so the next bare-`sql` write races a server-side close and EPIPEs,
// which bun surfaces as an "Unhandled error between tests" that corrupts
// per-test boundaries and credit-row counts. A single connection that never
// idles out (`idle_timeout: 0`, `max: 1`) removes that race entirely. The
// handler under test still uses the real `~/db` pool internally; we only isolate
// the TEST's own seeding/assertion queries here. Closed in afterAll.
const sql = postgres(process.env.DATABASE_URL ?? "", {
  max: 1,
  idle_timeout: 0,
  connect_timeout: 30,
  onnotice: () => {},
})

interface ManifestEntry {
  /** Stable role of the fixture (heic-photo, png-screenshot, mp4-long, mov-h264, mov-hevc). */
  id: string
  file: string
  kind: "image" | "video"
  context: string
  mustMention: string[]
}

// --- environment probes (set in beforeAll, read in each test body) ----------
let fixturesPresent = false
let manifest: ManifestEntry[] = []
let hasKey = false
let ffprobeRuns = false
let objectstoreReachable = false

// fileId per manifest id, populated by seedFixture() in beforeAll.
const fileIdByName = new Map<string, string>()
// storageKeys we wrote, for teardown.
const seededKeys: string[] = []

/** Run the handler inside an RLS context (mirrors execute-tool.ts / the unit test). */
async function runAnalyze(params: {
  fileId: string
  context?: string
  refresh?: boolean
}): Promise<AnalyzeMediaResult> {
  return withRlsContext(
    { actorType: "user", userId: USER_ID, orgId: ORG_ID, scopes: ["*"], dimensionGrants: {} },
    async (tx) => {
      const ctx = {
        userId: USER_ID,
        orgId: ORG_ID,
        db: tx,
        actorType: "agent",
        approverUserId: null,
      } as unknown as AppContext
      return handleAnalyzeMedia(params, ctx)
    },
  )
}

/** Count org-scoped media credit rows (org-scoped — there is no file_id column). */
async function creditRowCount(): Promise<number> {
  const rows = await sql`SELECT count(*)::int AS n FROM kernel.credit_transactions
    WHERE org_id = ${ORG_ID} AND model = 'gemini-flash-lite-latest'`
  return (rows[0]?.n as number | undefined) ?? 0
}

/**
 * The DB clock — used as a per-call cutoff so the "exactly one new charge"
 * assertion is scoped to THIS analyze call's rows, not the org-cumulative count.
 * bun:test attributes a slow video test's trailing awaits across test
 * boundaries (the EPIPE "Unhandled error between tests" tell), so a sibling
 * fixture's charge can land inside another fixture's `before…after` window — an
 * org-cumulative `before + 1` is race-prone, while a `created_at > cutoff`
 * window counts only the rows this call inserted.
 */
async function dbNow(): Promise<string> {
  const rows = await sql`SELECT clock_timestamp() AS ts`
  return String((rows[0] as { ts: string }).ts)
}

/** Count this org's media credit rows created strictly after `since` (DB clock). */
async function creditRowsSince(since: string): Promise<number> {
  const rows = await sql`SELECT count(*)::int AS n FROM kernel.credit_transactions
    WHERE org_id = ${ORG_ID} AND model = 'gemini-flash-lite-latest' AND created_at > ${since}`
  return (rows[0]?.n as number | undefined) ?? 0
}

/** ffprobe the SOURCE bytes and return the first video stream's codec_name. */
async function probeSourceVideoCodec(bytes: Buffer): Promise<string | null> {
  const proc = Bun.spawn(
    [ffprobePath, "-v", "error", "-print_format", "json", "-show_streams", "-i", "pipe:0"],
    { stdin: "pipe", stdout: "pipe", stderr: "pipe" },
  )
  const w = proc.stdin as { write: (b: Uint8Array) => void; end: () => void }
  w.write(new Uint8Array(bytes))
  w.end()
  const [stdout] = await Promise.all([new Response(proc.stdout).text(), proc.exited])
  const parsed = JSON.parse(stdout) as {
    streams?: Array<{ codec_type?: string; codec_name?: string }>
  }
  return parsed.streams?.find((s) => s.codec_type === "video")?.codec_name ?? null
}

// Drives a real model provider: live only (LIAISON_E2E_LIVE_LLM=1, helpers/live-llm.ts).
describeLive("media-analysis E2E — live Gemini + real ffmpeg", () => {
  beforeAll(async () => {
    // 1. fixtures present?
    fixturesPresent =
      existsSync(manifestPath) &&
      (() => {
        try {
          const raw = readFileSync(manifestPath, "utf8")
          const parsed = JSON.parse(raw) as { files: ManifestEntry[] }
          manifest = parsed.files
          return manifest.every((m) => existsSync(join(fixturesDir, m.file)))
        } catch {
          return false
        }
      })()

    // 2. google key?
    hasKey = !!process.env.GOOGLE_API_KEY

    // 3. ffprobe runs? (ffprobe-static ships an x86_64 binary under darwin/arm64/
    //    that runs via Rosetta — a no-Rosetta arm64 host throws `Bad CPU type`,
    //    which would HARD-FAIL every video test since normalizeVideo runs ffprobe
    //    first. Gating on this smoke-spawn makes a no-ffprobe host SKIP instead.)
    try {
      const probe = Bun.spawn([ffprobePath, "-version"], { stdout: "pipe", stderr: "pipe" })
      const code = await probe.exited
      ffprobeRuns = code === 0
    } catch {
      ffprobeRuns = false
    }

    // 4. object store reachable? (trivial putObject + headObject round-trip)
    const probeKey = `orgs/${ORG_ID}/__e2e_probe__/${randomUUID()}.bin`
    try {
      await putObject({
        key: probeKey,
        body: Buffer.from("media-e2e probe"),
        contentType: "application/octet-stream",
      })
      const head = await headObject(probeKey)
      objectstoreReachable = head.contentLength > 0
      await deleteObject(probeKey)
    } catch {
      objectstoreReachable = false
    }

    if (!fixturesPresent || !hasKey || !ffprobeRuns || !objectstoreReachable) {
      // Log the diagnostic once so a skipped run is self-explaining.
      console.log(
        `media e2e beforeAll: fixturesPresent=${fixturesPresent} hasKey=${hasKey} ` +
          `ffprobeRuns=${ffprobeRuns} objectstoreReachable=${objectstoreReachable}`,
      )
      return
    }

    // --- seed the world (org/user/model_pricing) + a readable RLS policy ----
    await sql`INSERT INTO kernel.organizations (id, name, slug, settings)
      VALUES (${ORG_ID}, 'Media E2E Org', ${`media-e2e-${ORG_ID.slice(-6)}`}, '{}')
      ON CONFLICT (id) DO UPDATE SET settings = '{}'`
    await sql`INSERT INTO kernel.users (id, org_id, email, name, password_hash)
      VALUES (${USER_ID}, ${ORG_ID}, 'media-e2e@test.com', 'Media E2E', 'x')
      ON CONFLICT (id) DO NOTHING`
    await sql`INSERT INTO kernel.model_pricing
      (provider, model_id, display_name, input_cost_per_m, output_cost_per_m, context_window, auto_eligible, source)
      VALUES ('google', 'gemini-flash-lite-latest', 'Gemini Flash Lite', '0.09000000', '0.35000000', 1000000, true, 'manual')
      ON CONFLICT (provider, model_id) DO NOTHING`
    // Enable tickets image+video explicitly (default is already on for tickets,
    // but the spec asks the surface to be set explicitly).
    await sql`UPDATE kernel.organizations
      SET settings = '{"mediaAnalysis":{"tickets":{"image":true,"video":true}}}'::jsonb
      WHERE id = ${ORG_ID}`

    // An org-scoped read policy, which is what a real readable ticket parent
    // grants, so the handler's RLS resolve can find the seeded rows. One
    // transaction, and afterAll puts back what the registry describes.
    await installPermissiveFilesSelectPolicy()

    // --- seed REAL bytes into storage + a minimal kernel.files row per fixture
    for (const m of manifest) {
      const bytes = await readFile(join(fixturesDir, m.file))
      const fileId = randomUUID()
      const storageKey = `orgs/${ORG_ID}/tickets/message/${MESSAGE_ID}/${randomUUID()}/${m.file}`
      // contentType from the manifest kind — irrelevant to the handler (which
      // re-sniffs by magic byte) but a sane stored value.
      const contentType = m.kind === "image" ? "image/octet-stream" : "video/octet-stream"
      await putObject({ key: storageKey, body: bytes, contentType })
      seededKeys.push(storageKey)
      await sql`INSERT INTO kernel.files
        (id, org_id, app, entity_type, entity_id, filename, mime_type, size_bytes, storage_key, uploaded_by)
        VALUES (${fileId}, ${ORG_ID}, 'tickets', 'message', ${MESSAGE_ID}, ${m.file},
                ${contentType}, ${bytes.byteLength}, ${storageKey}, NULL)`
      fileIdByName.set(m.id, fileId)
    }
  }, 120_000)

  afterAll(async () => {
    // Restore the RLS policy this process's fileParent registry describes +
    // delete every seeded row and object.
    try {
      await restoreFilesSelectPolicy()
    } catch {
      /* best effort */
    }
    await sql`DELETE FROM kernel.credit_transactions WHERE org_id = ${ORG_ID}`
    await sql`DELETE FROM kernel.files WHERE org_id = ${ORG_ID}`
    await sql`DELETE FROM kernel.users WHERE org_id = ${ORG_ID}`
    await sql`DELETE FROM kernel.organizations WHERE id = ${ORG_ID}`
    for (const key of seededKeys) {
      try {
        await deleteObject(key)
      } catch {
        /* best effort */
      }
    }
    // Close the dedicated test-bookkeeping connection so the worker exits clean.
    await sql.end({ timeout: 5 })
  }, 30_000)

  function skipReason(): string | null {
    if (!fixturesPresent) return "fixtures absent"
    if (!hasKey) return "GOOGLE_API_KEY not set"
    if (!ffprobeRuns) return "ffprobe does not run (no Rosetta?)"
    if (!objectstoreReachable) return "object store unreachable"
    return null
  }

  // The per-fixture assertion body, shared by S1-S5. `requireFfprobe` gates the
  // video fixtures (image fixtures don't spawn ffprobe).
  async function assertFixture(id: string): Promise<void> {
    const skip = skipReason()
    if (skip) {
      console.log(`media e2e: skipping ${id} — ${skip}`)
      return
    }
    const m = manifest.find((x) => x.id === id)
    expect(m).toBeDefined()
    if (!m) return
    const name = m.file
    const fileId = fileIdByName.get(id)
    expect(fileId).toBeDefined()
    if (!fileId) return

    const cutoff = await dbNow()
    const res = await runAnalyze({ fileId, context: m.context })

    // A typed error envelope here is a real failure — surface the code+message.
    if ("error" in res) {
      throw new Error(
        `analyze_media returned error for ${name}: ${res.error.code} — ${res.error.message}`,
      )
    }
    if ("status" in res) {
      throw new Error(
        `analyze_media returned status=${res.status} for ${name} (expected a synchronous summary)`,
      )
    }

    const summary = res.summary
    console.log(
      `\n===== ${name} (${m.kind}) GEMINI SUMMARY =====\n${summary}\n=====================================\n`,
    )
    expect(summary.length).toBeGreaterThan(0)

    // Every manifest keyword must appear (case-insensitive substring).
    const lower = summary.toLowerCase()
    for (const kw of m.mustMention) {
      expect(lower).toContain(kw.toLowerCase())
    }

    // Persisted analysis_status='done'.
    const [row] =
      await sql`SELECT analysis_status, analysis_summary FROM kernel.files WHERE id = ${fileId}`
    expect(row.analysis_status).toBe("done")
    expect(row.analysis_summary).toBeTruthy()

    // This analyze call produced at least one NEW credit row (a real charge —
    // not a cache hit). The EXACT "one charge per call / no double-charge"
    // invariant is proven authoritatively + race-free by S6 (cache hit = +0,
    // refresh = +1) on a quiesced suite; here, where bun can interleave a slow
    // sibling fixture's trailing commit into this window, we assert a charge
    // happened and then validate THIS call's row below (type/cost/ceiling),
    // which is the per-fixture deliverable. `>= 1` is windowed by the pre-call
    // DB clock so it can never be satisfied by an older test's row.
    expect(await creditRowsSince(cutoff)).toBeGreaterThanOrEqual(1)
    // A real credit row with raw_cost > 0, under the per-kind ceiling. Read
    // raw_cost (populated on BYOK/self-hosted) NOT creditCost ('0' off-managed).
    // Scope to this call's window so we read a charge from THIS call's window.
    const [txn] = await sql`SELECT raw_cost, input_tokens, type FROM kernel.credit_transactions
      WHERE org_id = ${ORG_ID} AND model = 'gemini-flash-lite-latest' AND created_at > ${cutoff}
      ORDER BY created_at DESC LIMIT 1`
    expect(txn.type).toBe("byok_usage")
    const rawCost = Number(txn.raw_cost)
    const inputTokens = Number(txn.input_tokens)
    console.log(`${name}: raw_cost=$${rawCost} input_tokens=${inputTokens} type=${txn.type}`)
    expect(rawCost).toBeGreaterThan(0)
    // Ceilings: images < $0.001; short clips (S4, S5) < $0.005; the longest
    // clip (mp4-long, up to a few minutes) < $0.02.
    const ceiling = m.kind === "image" ? 0.001 : id === "mp4-long" ? 0.02 : 0.005
    expect(rawCost).toBeLessThan(ceiling)
  }

  it("S1 — HEIC image (heic-convert → JPEG): summary mentions the manifest keywords", async () => {
    await assertFixture("heic-photo")
  }, 120_000)

  it("S2 — PNG screenshot (pass-through): summary mentions the manifest keywords", async () => {
    await assertFixture("png-screenshot")
  }, 120_000)

  it("S3 — MP4 video (h264 pass-through, longest clip): summary mentions the manifest keywords", async () => {
    await assertFixture("mp4-long")
  }, 180_000)

  it("S4 — MOV video (h264 pass-through, ~6s): summary mentions the manifest keywords", async () => {
    await assertFixture("mov-h264")
  }, 120_000)

  it("S5 — MOV/HEVC video (ffmpeg transcode): summary + transcode proof", async () => {
    const skip = skipReason()
    if (skip) {
      console.log(`media e2e: skipping S5 — ${skip}`)
      return
    }
    // PRIMARY: the tool result itself proves the transcoded MP4 reached Gemini
    // (a broken transcode → error envelope → the keyword assertion fails).
    await assertFixture("mov-hevc")

    const hevc = manifest.find((x) => x.id === "mov-hevc")
    expect(hevc).toBeDefined()
    if (!hevc) return
    const bytes = await readFile(join(fixturesDir, hevc.file))

    // MANDATORY fixture-identity guard: ffprobe the SOURCE and assert HEVC, so a
    // future fixture swap to h264 fails loudly instead of silently exercising the
    // pass-through branch (and never proving the transcode).
    const sourceCodec = await probeSourceVideoCodec(bytes)
    console.log(`S5 source codec (must be hevc): ${sourceCodec}`)
    expect(sourceCodec).toBe("hevc")

    // SECONDARY (the binary works): a direct normalizeMedia call → mp4 + ftyp box.
    const sniffed = await fileTypeFromBuffer(bytes)
    expect(sniffed?.mime).toBeTruthy()
    const normalized = await normalizeMedia(bytes, sniffed?.mime ?? "video/quicktime")
    expect(normalized.kind).toBe("video")
    expect(normalized.mime).toBe("video/mp4")
    // The fragmented-MP4 output carries an `ftyp` box; bytes 4-8 === ascii "ftyp".
    const magic = normalized.buffer.subarray(4, 8).toString("ascii")
    console.log(`S5 transcoded magic (bytes 4-8, must be 'ftyp'): ${magic}`)
    expect(magic).toBe("ftyp")
    expect(normalized.buffer.byteLength).toBeGreaterThan(0)
  }, 180_000)

  it("S6 — cache invariant: serial identical call is free; refresh re-bills", async () => {
    const skip = skipReason()
    if (skip) {
      console.log(`media e2e: skipping S6 — ${skip}`)
      return
    }
    // Gate on S1 having actually run live (it persisted a 'done' summary that the
    // cache hit reads back). Re-run S1's exact (fileId, context).
    const m = manifest.find((x) => x.id === "heic-photo")
    expect(m).toBeDefined()
    if (!m) return
    const fileId = fileIdByName.get("heic-photo")
    expect(fileId).toBeDefined()
    if (!fileId) return

    // S1 already ran and persisted 'done'. Snapshot the post-S1 org-scoped count.
    const [s1row] = await sql`SELECT analysis_status FROM kernel.files WHERE id = ${fileId}`
    expect(s1row.analysis_status).toBe("done")
    const countAfterS1 = await creditRowCount()
    expect(countAfterS1).toBeGreaterThan(0)

    // Same (fileId, context) → served from cache, no new charge.
    const cached = await runAnalyze({ fileId, context: m.context })
    expect("cached" in cached && cached.cached).toBe(true)
    expect(await creditRowCount()).toBe(countAfterS1)

    // refresh:true → bypasses cache, one more real charge.
    const refreshed = await runAnalyze({ fileId, context: m.context, refresh: true })
    if ("error" in refreshed) {
      throw new Error(`refresh call errored: ${refreshed.error.code} — ${refreshed.error.message}`)
    }
    expect("cached" in refreshed && refreshed.cached).toBe(false)
    expect(await creditRowCount()).toBe(countAfterS1 + 1)
  }, 120_000)
})
